import unittest
from pathlib import Path
from streamlit.testing.v1 import AppTest

APP = str(Path(__file__).resolve().parents[1] / 'app.py')


def button(app, label):
    return next(b for b in app.button if b.label == label)


class InterfaceTests(unittest.TestCase):
    def test_guided_flow_from_intro_to_conclusion(self):
        app = AppTest.from_file(APP).run()
        self.assertEqual(len(app.exception), 0)
        self.assertEqual(app.title[0].value, 'Qual é o problema?')
        for screen in ('novidade', 'afetados', 'impactos', 'solucoes', 'intro_objetivo',
                       'intro_voltagem', 'intro_quartzo', 'intro_geometria'):
            button(app, 'Continuar →').click().run()
            self.assertEqual(app.session_state['screen'], screen)
            self.assertEqual(len(app.exception), 0)

        button(app, 'Abrir demonstração rápida →').click().run()
        self.assertTrue(any('Computador desta simulação' in m.value for m in app.markdown))
        self.assertTrue(any('EnergySim' in m.value for m in app.markdown))
        self.assertTrue(any(s.value == 'Evolução da simulação' for s in app.subheader))
        self.assertEqual(len(app.get('vega_lite_chart')), 3)
        self.assertFalse(any(b.label == 'Ver comparativo →' for b in app.button))
        self.assertTrue(button(app, '2. Simular otimização').disabled)
        initial = app.session_state['quick_demo'].snapshot()['power']['total_w']
        button(app, '1. Mostrar consumo extra').click().run()
        self.assertEqual(len(app.exception), 0)
        self.assertTrue(any('Algo está gastando' in m.value for m in app.markdown))
        cause_panel = next(m.value for m in app.markdown if 'O que pode estar consumindo a mais?' in m.value)
        self.assertIn('sincronização de arquivos', cause_panel)
        self.assertIn('abas reproduzindo vídeo', cause_panel)
        self.assertFalse(any('O que foi feito na otimização?' in m.value for m in app.markdown))
        self.assertTrue(any('51%' in m.value and 'Placa gráfica: 45%' in m.value for m in app.markdown))
        self.assertNotEqual(initial, app.session_state['quick_demo'].snapshot()['power']['total_w'])
        before_observation = app.session_state['quick_demo'].snapshot()
        button(app, 'Avançar 2 min').click().run()
        after_observation = app.session_state['quick_demo'].snapshot()
        self.assertEqual(after_observation['elapsed_s'] - before_observation['elapsed_s'], 120)
        self.assertGreater(after_observation['kwh'], before_observation['kwh'])
        self.assertEqual(after_observation['power']['total_w'], before_observation['power']['total_w'])
        button(app, '2. Simular otimização').click().run()
        self.assertEqual(len(app.exception), 0)
        self.assertEqual(initial, app.session_state['quick_demo'].snapshot()['power']['total_w'])
        explanation = next(m.value for m in app.markdown if 'O que foi feito na otimização?' in m.value)
        self.assertIn('Verificar processos', explanation)
        self.assertIn('90 W para 0 W', explanation)
        self.assertIn('voltou ao nível da tarefa original', explanation)
        self.assertTrue(any('11%' in m.value and 'Placa gráfica: 4%' in m.value for m in app.markdown))
        self.assertEqual(app.session_state['quick_demo'].before, after_observation)
        result = app.session_state['quick_demo'].comparison()
        button(app, 'Avançar 30 s').click().run()
        self.assertEqual(app.session_state['quick_demo'].comparison(), result)
        button(app, 'Ver comparativo →').click().run()
        self.assertEqual(app.title[0].value, 'Antes e depois da otimização')
        self.assertTrue(any('51% → 11%' in m.value and '45% → 4%' in m.value for m in app.markdown))
        self.assertTrue(any('19,44' in m.value for m in app.markdown))
        app.run()
        self.assertTrue(any('19,44' in m.value for m in app.markdown))
        button(app, '← Voltar').click().run()
        app.number_input(key='demo_tariff').set_value(1.8).run()
        button(app, 'Ver comparativo →').click().run()
        self.assertTrue(any('38,88' in m.value for m in app.markdown))

        button(app, 'Ir para o teste de estresse →').click().run()
        self.assertTrue(any('Configurações dos computadores' == item.value for item in app.subheader))
        self.assertEqual(sum('**Processador**' in m.value for m in app.markdown), 2)
        button(app, 'Iniciar teste de estresse →').click().run()
        self.assertEqual(app.session_state['screen'], 'teste_estresse_execucao')
        button(app, '⏱️ Avançar 10s').click().run()
        button(app, '🏁 Finalizar teste e ver resultado →').click().run()
        self.assertEqual(app.session_state['screen'], 'teste_estresse_resultado')
        button(app, 'Por que existiu essa diferença? →').click().run()
        self.assertEqual(app.session_state['screen'], 'teste_estresse_explicacao')
        button(app, 'Laboratório de experimentos →').click().run()
        self.assertEqual(app.session_state['screen'], 'laboratorio')
        self.assertEqual(len(app.exception), 0)
        button(app, 'Continuar →').click().run()
        self.assertEqual(app.session_state['screen'], 'conclusao')
        button(app, 'Recomeçar roteiro').click().run()
        self.assertEqual(app.session_state['screen'], 'intro_problema')
        self.assertEqual(len(app.exception), 0)
        self.assertNotIn('quick_demo', app.session_state)
